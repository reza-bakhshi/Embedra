package io.github.rezabakhshi.embedra.build;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNotEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.util.HexFormat;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

class FoundationAutomationTest {
    private static final Path PROJECT =
        Path.of(System.getProperty("embedra.projectDir")).toAbsolutePath().normalize();

    @TempDir
    Path temporaryDirectory;

    @Test
    void ciPinsInputsAndSeparatesPureGhidraAndReleaseEvidence() throws IOException {
        String workflow = Files.readString(PROJECT.resolve(".github/workflows/ci.yml"),
            StandardCharsets.UTF_8);

        assertTrue(workflow.contains("permissions:\n  contents: read"));
        assertFalse(workflow.contains("pull_request_target:"));
        assertFalse(workflow.matches("(?s).*uses: [^\\n]+@v[0-9]+.*"));
        assertTrue(workflow.contains("actions/checkout@9c091bb21b7c1c1d1991bb908d89e4e9dddfe3e0"));
        assertTrue(workflow.contains("actions/setup-java@de7274f081f381c8f8158605e0321c36c376e2e6"));
        assertTrue(workflow.contains("actions/upload-artifact@bbbca2ddaa5d8feaa63e36b76fdaad77386f024f"));
        assertTrue(workflow.contains("93a5d11a9ad510622acaaf908c556a7b9b764d338e78a7567f3689bf5081fd54"));
        assertTrue(workflow.contains("pureTest"));
        assertTrue(workflow.contains("ghidraIntegrationTest"));
        assertTrue(workflow.contains("validate-fixture-provenance.sh"));
        assertTrue(workflow.contains("validate-handoff.sh"));
        assertTrue(workflow.contains("buildExtension"));
    }

    @Test
    void fixturePolicyRejectsUnmanifestedAndAcceptsCompleteFixtures() throws Exception {
        Path fixtures = Files.createDirectories(temporaryDirectory.resolve("fixtures"));
        Path firmware = Files.write(fixtures.resolve("sample.bin"), new byte[] {1, 2, 3});

        assertNotEquals(0, runScript("scripts/validate-fixture-provenance.sh", fixtures));

        String manifest = """
            {
              "fixtureId": "synthetic.sample",
              "sha256": "%s",
              "target": "synthetic-device",
              "inputFormat": "synthetic",
              "origin": "Generated by FoundationAutomationTest",
              "license": "Apache-2.0",
              "redistributionStatus": "REDISTRIBUTABLE",
              "generatorRevision": "test-source",
              "generationCommand": "unit-test deterministic bytes 01 02 03",
              "toolchain": "JDK 21 test fixture",
              "oracleCommands": ["sha256sum sample.bin"],
              "expectedSnapshot": "none",
              "requirements": ["T007"]
            }
            """.formatted(sha256(Files.readAllBytes(firmware)));
        Files.writeString(fixtures.resolve("sample.bin.manifest.json"), manifest,
            StandardCharsets.UTF_8);

        assertEquals(0, runScript("scripts/validate-fixture-provenance.sh", fixtures));
    }

    @Test
    void continuityValidatorAcceptsHandoffAndRejectsSpecificationDrift() throws Exception {
        assertEquals(0, runScript("scripts/validate-handoff.sh", PROJECT));
        Path copy = temporaryDirectory.resolve("handoff");
        Files.createDirectories(copy.resolve(".embedra/evidence/tasks"));
        Files.copy(PROJECT.resolve("Embedra-SpecKit.md"), copy.resolve("Embedra-SpecKit.md"));
        Files.copy(PROJECT.resolve("PROJECT_STATE.md"), copy.resolve("PROJECT_STATE.md"));
        Files.copy(PROJECT.resolve(".embedra/state.json"), copy.resolve(".embedra/state.json"));
        Files.copy(PROJECT.resolve(".embedra/evidence/commands.jsonl"),
            copy.resolve(".embedra/evidence/commands.jsonl"));
        Path currentEvidence = PROJECT.resolve(".embedra/evidence/tasks/T006.md");
        Files.copy(currentEvidence, copy.resolve(".embedra/evidence/tasks/T006.md"),
            StandardCopyOption.REPLACE_EXISTING);
        Files.writeString(copy.resolve("Embedra-SpecKit.md"), "\nDRIFT\n",
            StandardCharsets.UTF_8, java.nio.file.StandardOpenOption.APPEND);

        assertNotEquals(0, runScript("scripts/validate-handoff.sh", copy));
    }

    @Test
    void continuityValidatorRejectsMissingCompletedTaskEvidence() throws Exception {
        Path copy = temporaryDirectory.resolve("missing-evidence-handoff");
        Files.createDirectories(copy.resolve(".embedra/evidence/tasks"));
        Files.copy(PROJECT.resolve("Embedra-SpecKit.md"), copy.resolve("Embedra-SpecKit.md"));
        Files.copy(PROJECT.resolve("PROJECT_STATE.md"), copy.resolve("PROJECT_STATE.md"));
        Files.copy(PROJECT.resolve(".embedra/state.json"), copy.resolve(".embedra/state.json"));
        Files.copy(PROJECT.resolve(".embedra/evidence/commands.jsonl"),
            copy.resolve(".embedra/evidence/commands.jsonl"));

        assertNotEquals(0, runScript("scripts/validate-handoff.sh", copy));
    }

    private static int runScript(String relativeScript, Path argument)
            throws IOException, InterruptedException {
        Process process = new ProcessBuilder("sh", PROJECT.resolve(relativeScript).toString(),
            argument.toString()).redirectErrorStream(true).start();
        process.getInputStream().transferTo(java.io.OutputStream.nullOutputStream());
        return process.waitFor();
    }

    private static String sha256(byte[] bytes) {
        try {
            return HexFormat.of().formatHex(MessageDigest.getInstance("SHA-256").digest(bytes));
        }
        catch (NoSuchAlgorithmException exception) {
            throw new AssertionError(exception);
        }
    }
}
